#!/usr/bin/env bash
set -uo pipefail

INSTALLER_PATH="$HOME/.local/bin/install-omarchy-gtk-theme-sync"
HOOK_DIR="$HOME/.config/omarchy/hooks/theme-set.d"
HOOK_PATH="$HOOK_DIR/sync-gtk"
OMARCHY_THEME_DIR="$HOME/.local/state/omarchy/current/theme"
OMARCHY_COLORS_FILE="$OMARCHY_THEME_DIR/colors.toml"
OMARCHY_THEME_NAME_FILE="$HOME/.local/state/omarchy/current/theme.name"
GTK3_CSS_DIR="$HOME/.config/gtk-3.0"
GTK4_CSS_DIR="$HOME/.config/gtk-4.0"

log() {
  printf 'omarchy-gtk-theme-sync: %s\n' "$*" >&2
}

usage() {
  cat <<'USAGE'
Usage:
  install-omarchy-gtk-theme-sync          Install the Omarchy hook and sync GTK now
  install-omarchy-gtk-theme-sync --sync   Sync GTK with the current Omarchy theme now

The hook runs after `omarchy theme set ...`, generates
~/.config/gtk-3.0/gtk.css and ~/.config/gtk-4.0/gtk.css from the active
Omarchy colors.toml, and calls gsettings to set dark/light mode.
USAGE
}

sync_gtk() {
  if [[ ! -f "$OMARCHY_COLORS_FILE" ]]; then
    log "No Omarchy colors file found at $OMARCHY_COLORS_FILE"
    return 0
  fi

  if ! command -v python3 >/dev/null; then
    log "python3 is required to generate GTK CSS"
    return 1
  fi

  mkdir -p "$GTK3_CSS_DIR" "$GTK4_CSS_DIR"

  python3 - "$OMARCHY_COLORS_FILE" "$OMARCHY_THEME_DIR" "$GTK3_CSS_DIR/gtk.css" "$GTK4_CSS_DIR/gtk.css" <<'PYTHON'
import re
import subprocess
import sys
from pathlib import Path

colors_path = Path(sys.argv[1])
theme_dir = Path(sys.argv[2])
gtk3_css_path = Path(sys.argv[3])
gtk4_css_path = Path(sys.argv[4])

HEX_RE = re.compile(r"^#[0-9a-fA-F]{6}$")


def read_colors(path):
    colors = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if value.startswith(('"', "'")):
            quote = value[0]
            value = value[1:].split(quote, 1)[0]
        else:
            value = value.split("#", 1)[0].strip()
        if HEX_RE.match(value):
            colors[key] = value.upper()
    return colors


def color(colors, key, fallback):
    value = colors.get(key, fallback)
    return value.upper() if HEX_RE.match(value) else fallback.upper()


def rgb(hex_color):
    h = hex_color.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


def rgba(hex_color, opacity):
    r, g, b = rgb(hex_color)
    return f"rgba({r}, {g}, {b}, {opacity})"


def mix(a, b, amount):
    ar, ag, ab = rgb(a)
    br, bg, bb = rgb(b)
    return "#{:02X}{:02X}{:02X}".format(
        max(0, min(255, round(ar + (br - ar) * amount))),
        max(0, min(255, round(ag + (bg - ag) * amount))),
        max(0, min(255, round(ab + (bb - ab) * amount))),
    )


colors = read_colors(colors_path)
is_light = (theme_dir / "light.mode").exists()

bg = color(colors, "background", "#FAFAFA" if is_light else "#111111")
fg = color(colors, "foreground", "#1A1A1A" if is_light else "#EEEEEE")
accent = color(colors, "accent", color(colors, "color4", "#3584E4"))
red = color(colors, "color1", "#E5534B")
green = color(colors, "color2", "#33D17A")
yellow = color(colors, "color3", "#F6D32D")
blue = color(colors, "color4", accent)
magenta = color(colors, "color5", "#C061CB")
cyan = color(colors, "color6", "#26A1A2")
muted = color(colors, "color8", mix(bg, fg, 0.45))
selection_bg = color(colors, "selection_background", mix(bg, accent, 0.35))
selection_fg = color(colors, "selection_foreground", fg)

surface_0 = mix(bg, fg, 0.04)
surface_1 = mix(bg, fg, 0.08)
surface_2 = mix(bg, fg, 0.14)

# GTK3 CSS
gtk3_css = f"""\
/* Auto-generated by install-omarchy-gtk-theme-sync */
@define-color theme_bg_color {bg};
@define-color theme_fg_color {fg};
@define-color theme_base_color {surface_0};
@define-color theme_selected_bg_color {selection_bg};
@define-color theme_selected_fg_color {selection_fg};
@define-color theme_link_color {blue};
@define-color theme_link_visited_color {magenta};
@define-color theme_warning_color {yellow};
@define-color theme_error_color {red};
@define-color theme_success_color {green};
@define-color insensitive_fg_color {muted};
@define-color borders {surface_2};
@define-color unfocused_borders {surface_1};

/* Window decorations */
headerbar {{
  background-color: {surface_0};
  border-bottom-color: {surface_2};
}}

/* Buttons */
button.suggested-action {{
  background-color: {accent};
  color: {mix(accent, "#000000", 0.85)};
}}
button.suggested-action:hover {{
  background-color: {mix(accent, fg, 0.15)};
}}
button.destructive-action {{
  background-color: {red};
  color: {mix(red, "#000000", 0.85)};
}}

/* Selection */
:selected {{
  background-color: {selection_bg};
  color: {selection_fg};
}}

/* Scrollbars */
scrollbar slider {{
  background-color: {muted};
  border-radius: 99px;
}}
scrollbar slider:hover {{
  background-color: {fg};
}}

/* Links */
a {{
  color: {blue};
}}
a:hover {{
  color: {mix(blue, fg, 0.15)};
}}
"""

gtk3_css_path.write_text(gtk3_css)
print(f"wrote {gtk3_css_path}")

# GTK4 CSS
gtk4_css = f"""\
/* Auto-generated by install-omarchy-gtk-theme-sync */
@define-color window_bg_color {bg};
@define-color window_fg_color {fg};
@define-color view_bg_color {surface_0};
@define-color view_fg_color {fg};
@define-color headerbar_bg_color {surface_0};
@define-color headerbar_fg_color {fg};
@define-color headerbar_backdrop_color {bg};
@define-color headerbar_shade_color {rgba(bg, 0.36)};
@define-color card_bg_color {surface_1};
@define-color card_fg_color {fg};
@define-color card_shade_color {rgba(bg, 0.36)};
@define-color dialog_bg_color {bg};
@define-color dialog_fg_color {fg};
@define-color popover_bg_color {bg};
@define-color popover_fg_color {fg};
@define-color shade_color {rgba(bg, 0.25)};
@define-color scrollbar_outline_color {rgba(bg, 0.5)};
@define-color sidebar_bg_color {surface_0};
@define-color sidebar_fg_color {fg};
@define-color sidebar_backdrop_color {bg};
@define-color sidebar_shade_color {rgba(bg, 0.25)};
@define-color sidebar_view_bg_color {surface_0};
@define-color sidebar_view_fg_color {fg};
@define-color accent_bg_color {accent};
@define-color accent_fg_color {mix(accent, "#000000", 0.85)};
@define-color accent_color {accent};
@define-color destructive_bg_color {red};
@define-color destructive_fg_color {mix(red, "#000000", 0.85)};
@define-color success_bg_color {green};
@define-color success_fg_color {mix(green, "#000000", 0.85)};
@define-color warning_bg_color {yellow};
@define-color warning_fg_color {mix(yellow, "#000000", 0.85)};
@define-color error_bg_color {red};
@define-color error_fg_color {mix(red, "#000000", 0.85)};
@define-color window_bg_color {bg};
@define-color window_fg_color {fg};
@define-color window_handle_color {muted};
@define-color switcher_slider_bg_color {accent};
@define-color switcher_slider_fg_color {mix(accent, "#000000", 0.85)};

/* Selection */
:selected {{
  background-color: {selection_bg};
  color: {selection_fg};
}}

/* Buttons */
button.suggested-action {{
  background-color: {accent};
  color: {mix(accent, "#000000", 0.85)};
}}
button.suggested-action:hover {{
  background-color: {mix(accent, fg, 0.15)};
}}
button.destructive-action {{
  background-color: {red};
  color: {mix(red, "#000000", 0.85)};
}}

/* Links */
a {{
  color: {blue};
}}
a:hover {{
  color: {mix(blue, fg, 0.15)};
}}

/* Scrollbars */
scrollbar slider {{
  background-color: {muted};
}}
scrollbar slider:hover {{
  background-color: {fg};
}}

/* Headers */
headerbar {{
  background-color: {surface_0};
}}
"""

gtk4_css_path.write_text(gtk4_css)
print(f"wrote {gtk4_css_path}")

# Set gsettings for dark/light mode
try:
    mode = "light" if is_light else "dark"
    subprocess.run(
        ["gsettings", "set", "org.gnome.desktop.interface", "color-scheme", f"prefer-{mode}"],
        check=False, capture_output=True,
    )
    subprocess.run(
        ["gsettings", "set", "org.gnome.desktop.interface", "gtk-theme", "Adwaita" if is_light else "Adwaita-dark"],
        check=False, capture_output=True,
    )
    print(f"set gsettings color-scheme to prefer-{mode}")
except Exception:
    print("warning: gsettings not available (no DBUS session?)")
PYTHON

  log "Synced GTK to the current Omarchy theme."
}

install_hook() {
  local source_path target_path

  mkdir -p "$HOME/.local/bin" "$HOOK_DIR"

  source_path=$(realpath -m "${BASH_SOURCE[0]}")
  target_path=$(realpath -m "$INSTALLER_PATH")
  if [[ "$source_path" != "$target_path" ]]; then
    cp "$source_path" "$INSTALLER_PATH"
  fi
  chmod +x "$INSTALLER_PATH"

  cat >"$HOOK_PATH" <<'HOOK'
#!/usr/bin/env bash
exec "$HOME/.local/bin/install-omarchy-gtk-theme-sync" --sync "$@"
HOOK
  chmod +x "$HOOK_PATH"

  log "Installed hook at $HOOK_PATH"
  "$INSTALLER_PATH" --sync
}

case "${1:-}" in
  ""|--install)
    install_hook
    ;;
  --sync)
    shift
    sync_gtk "$@"
    ;;
  -h|--help)
    usage
    ;;
  *)
    usage >&2
    exit 2
    ;;
esac
